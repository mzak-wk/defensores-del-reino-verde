    // ==========================
    // Precios tienda
    // ==========================
    public int CurrentPriceHP()
    {
        int rawPrice = Mathf.CeilToInt(basePriceHP * Mathf.Pow(priceFactor, hpLevel));
        return Mathf.Min(maxUpgradePrice, rawPrice);
    }

    public int CurrentPriceSpeed()
    {
        int rawPrice = Mathf.CeilToInt(basePriceSpeed * Mathf.Pow(priceFactor, speedLevel));
        return Mathf.Min(maxUpgradePrice, rawPrice);
    }

    public int CurrentPriceResist() // ahora es el IMÁN
    {
        int rawPrice = Mathf.CeilToInt(basePriceResist * Mathf.Pow(priceFactor, resistLevel));
        return Mathf.Min(maxUpgradePrice, rawPrice);
    }

    // ==========================
    // Multiplicadores tienda
    // ==========================
    public void RecomputeShopMultipliers()
    {
        // Velocidad de movimiento: +5% por nivel
        moveSpeedMul = 1f + speedLevel * 0.15f;

        // Dureza ya no se usa, lo dejamos a 1
        damageTakenMul = 1f;

        // Imán: +1 de radio y +5 de velocidad por nivel
        magnetRadiusBonus = resistLevel * 1f;
        magnetPullBonus   = resistLevel * 5f;

        // Regeneración: base +0.1 cada 5 niveles de vida
        int regenSteps = hpLevel / 5; // enteros
        regenPerSecond = baseRegenPerSecond + regenSteps * 0.1f;
    }

    public float GetMoveSpeedMultiplier()   => moveSpeedMul;
    public float GetDamageTakenMultiplier() => damageTakenMul;
    public float GetMagnetRadiusBonus()     => magnetRadiusBonus;
    public float GetMagnetPullBonus()       => magnetPullBonus;

    // ==========================
    // Persistencia Roguelite
    // ==========================
    public void AddTempGold(int amount)
    {
        tempGold += amount;
        Debug.Log($"[GameSession] TempGold +{amount} → {tempGold}");
    }

    public void AddTempXP(float amount)
    {
        tempXP += amount;
        Debug.Log($"[GameSession] TempXP +{amount} → {tempXP}");
    }

    public void ConsolidateRunRewards()
    {
        gold += tempGold;
        playerXP += tempXP;

        // Procesar level-ups pendientes
        while (playerXP >= playerXpToNext)
        {
            playerXP -= playerXpToNext;
            playerLevel++;
            playerXpToNext = Mathf.Ceil(playerXpToNext * 1.6f);
        }

        Debug.Log($"[GameSession] Consolidado: gold={gold}, xp={playerXP}, level={playerLevel}");
        DiscardRunRewards();
    }

    public void DiscardRunRewards()
    {
        tempGold = 0;
        tempXP = 0f;
    }

    public void FullHeal()
    {
        playerCurrentHP = playerMaxHP;
        Debug.Log("[GameSession] FullHeal aplicado.");
    }

    // ==========================
    // Gasto / Upgrades
    // ==========================
    public bool TrySpend(int amount)
    {
        if (gold < amount) return false;
        gold -= amount;
        return true;
    }

    public bool ApplyHpUpgrade()
    {
        if (hpLevel >= maxHpLevel) return false;

        int cost = CurrentPriceHP();
        if (!TrySpend(cost)) return false;

        hpLevel++;

        // +20 de vida máx por nivel
        playerMaxHP += 30f;
        playerCurrentHP = Mathf.Min(playerCurrentHP + 20f, playerMaxHP);

        RecomputeShopMultipliers();
        return true;
    }

    public bool ApplySpeedUpgrade()
    {
        if (speedLevel >= maxSpeedLevel) return false;

        int cost = CurrentPriceSpeed();
        if (!TrySpend(cost)) return false;

        speedLevel++;
        RecomputeShopMultipliers();
        return true;
    }

    // OJO: Resist ahora es el IMÁN (+rango y +pull speed)
    public bool ApplyResistUpgrade()
    {
        if (resistLevel >= maxResistLevel) return false;

        int cost = CurrentPriceResist();
        if (!TrySpend(cost)) return false;

        resistLevel++;
        RecomputeShopMultipliers();
        return true;
    }

    // Sobrecargas legacy
    public bool ApplyHpUpgrade(int _ignoredCost)       => ApplyHpUpgrade();
    public bool ApplySpeedUpgrade(int _ignoredCost)    => ApplySpeedUpgrade();
    public bool ApplyResistUpgrade(int _ignoredCost)   => ApplyResistUpgrade();
    public bool ApplyHpUpgrade(float _ignoredCost)     => ApplyHpUpgrade();
    public bool ApplySpeedUpgrade(float _ignoredCost)  => ApplySpeedUpgrade();
    public bool ApplyResistUpgrade(float _ignoredCost) => ApplyResistUpgrade();

    // ==========================
    // Gestión de Armas
    // ==========================
    public void UnlockWeapon(WeaponData weapon)
    {
        if (weapon == null) return;
        if (!unlockedWeapons.Contains(weapon.WeaponId))
        {
            unlockedWeapons.Add(weapon.WeaponId);
            Debug.Log($"[GameSession] Arma desbloqueada: {weapon.DisplayName}");
        }
    }

    public void EquipWeapon(WeaponData weapon)
    {
        if (weapon == null || !IsWeaponUnlocked(weapon)) return;
        equippedWeapon = weapon;
        equippedWeaponId = weapon.WeaponId;
        equippedWeaponIndex = weapon.WeaponIndex;
        Debug.Log($"[GameSession] Arma equipada: {weapon.DisplayName} (index={weapon.WeaponIndex})");
    }

    public bool IsWeaponUnlocked(WeaponData weapon)
    {
        if (weapon == null) return false;
        return unlockedWeapons.Contains(weapon.WeaponId);
    }

    // ==========================
    // Completar Nivel / Progresión
    // ==========================
    /// <summary>
    /// Completa el nivel actual: guarda progreso, limpia estado temporal y transiciona al HUB.
    /// Se invoca desde BossRewardUI al seleccionar un arma de recompensa.
    /// </summary>
    public void CompleteLevel()
    {
        // Guardar progreso persistentemente
        if (SaveManager.Instance != null)
        {
            SaveManager.Instance.SaveCurrentGame();
            Debug.Log("[GameSession] Progreso guardado.");
        }
        else
        {
            Debug.LogWarning("[GameSession] SaveManager no disponible para guardar progreso.");
        }

        // Limpiar estado temporal de la carrera actual
        tempGold = 0;
        tempXP = 0;
        Debug.Log("[GameSession] Estado temporal limpiado (tempGold y tempXP reseteados).");

        // Transicionar al LevelHUB
        Debug.Log("[GameSession] Transitioning to LevelHUB...");
        SceneManager.LoadScene("LevelHUB");
    }

