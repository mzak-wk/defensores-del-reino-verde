    // ==========================
    // Gestión de Ítems
    // ==========================
    public bool EquipItem(string itemId)
    {
        if (string.IsNullOrEmpty(itemId)) return false;

        for (int i = 0; i < equippedItems.Length; i++)
        {
            if (string.IsNullOrEmpty(equippedItems[i]))
            {
                equippedItems[i] = itemId;
                Debug.Log($"[GameSession] Ítem '{itemId}' equipado en slot {i}.");
                return true;
            }
        }
        Debug.LogWarning("[GameSession] No hay slots libres para equipar ítem.");
        return false;
    }

    public bool UnequipItem(int slotIndex)
    {
        if (slotIndex < 0 || slotIndex >= equippedItems.Length) return false;
        if (string.IsNullOrEmpty(equippedItems[slotIndex])) return false;

        string removedId = equippedItems[slotIndex];
        equippedItems[slotIndex] = null;
        Debug.Log($"[GameSession] Ítem '{removedId}' desequipado del slot {slotIndex}.");
        return true;
    }

    public bool IsItemEquipped(string itemId)
    {
        if (string.IsNullOrEmpty(itemId)) return false;
        for (int i = 0; i < equippedItems.Length; i++)
        {
            if (equippedItems[i] == itemId) return true;
        }
        return false;
    }

    public int GetEquippedSlotIndex(string itemId)
    {
        if (string.IsNullOrEmpty(itemId)) return -1;
        for (int i = 0; i < equippedItems.Length; i++)
        {
            if (equippedItems[i] == itemId) return i;
        }
        return -1;
    }

    // ==========================
    // Gestión de Niveles de Ítems
    // ==========================
    public int GetItemLevel(string itemId)
    {
        if (string.IsNullOrEmpty(itemId)) return 0;
        int index = itemLevelKeys.IndexOf(itemId);
        return index >= 0 ? itemLevelValues[index] : 0;
    }

    public void SetItemLevel(string itemId, int level)
    {
        if (string.IsNullOrEmpty(itemId)) return;
        int index = itemLevelKeys.IndexOf(itemId);
        if (index >= 0)
        {
            itemLevelValues[index] = level;
        }
        else
        {
            itemLevelKeys.Add(itemId);
            itemLevelValues.Add(level);
        }
    }

    public bool HasItem(string itemId)
    {
        return GetItemLevel(itemId) > 0;
    }

    public int GetMaxLevelForRarity(ItemRarity rarity)
    {
        switch (rarity)
        {
            case ItemRarity.Comun: return 999;
            case ItemRarity.Raro: return 5;
            case ItemRarity.Epico: return 2;
            case ItemRarity.Legendario: return 1;
            default: return 1;
        }
    }

