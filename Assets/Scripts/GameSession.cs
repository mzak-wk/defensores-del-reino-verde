    // ==========================
    // Ciclo de vida
    // ==========================
    void Awake()
    {
        // Si ya existe una instancia válida que no somos nosotros, destruirnos
        if (_instance != null && _instance != this)
        {
            Destroy(gameObject);
            return;
        }

        // Si _instance es null, buscar en TODAS las escenas por si hay otra
        // (resuelve el caso donde la escena tiene un GameSession embebido)
        if (_instance == null)
        {
            var allSessions = FindObjectsByType<GameSession>(FindObjectsSortMode.None);
            foreach (var session in allSessions)
            {
                if (session != this)
                {
                    Destroy(gameObject);
                    return;
                }
            }
        }

        _instance = this;
        DontDestroyOnLoad(gameObject);

        // Inicializar datos por defecto
        if (highestLevelUnlocked < 1) highestLevelUnlocked = 1;
        if (unlockedItems == null) unlockedItems = new System.Collections.Generic.List<string>();
        if (equippedItems == null || equippedItems.Length != 3) equippedItems = new string[3];

        // Snapshot inicial
        _initial_playerMaxHP       = playerMaxHP;
        _initial_playerCurrentHP   = playerCurrentHP;
        _initial_gold              = gold;
        _initial_hpLevel           = hpLevel;
        _initial_speedLevel        = speedLevel;
        _initial_resistLevel       = resistLevel;
        _initial_basePriceHP       = basePriceHP;
        _initial_basePriceSpeed    = basePriceSpeed;
        _initial_basePriceResist   = basePriceResist;
        _initial_priceFactor       = priceFactor;
        _initial_totalMinutesPlayed= totalMinutesPlayed;
        _initial_playerLevel       = playerLevel;
        _initial_playerXP          = playerXP;
        _initial_playerXpToNext    = playerXpToNext;
        _initial_baseRegen         = baseRegenPerSecond;
        _initial_regen             = regenPerSecond;
        _initial_equippedWeaponId  = equippedWeaponId;
        _initial_equippedWeaponIndex = equippedWeaponIndex;
        _initial_highestLevelUnlocked = highestLevelUnlocked;
        _initial_unlockedItems = new System.Collections.Generic.List<string>(unlockedItems);
        _initial_equippedItems = new string[3];
        if (equippedItems != null)
        {
            for (int i = 0; i < Mathf.Min(3, equippedItems.Length); i++)
                _initial_equippedItems[i] = equippedItems[i];
        }

        _initial_itemLevelKeys = new System.Collections.Generic.List<string>(itemLevelKeys);
        _initial_itemLevelValues = new System.Collections.Generic.List<int>(itemLevelValues);

        RecomputeShopMultipliers();

        Debug.Log($"[GameSession] Awake snapshot saved.");

#if UNITY_EDITOR
        if (unlockAllWeaponsForTesting)
        {
            UnlockAllWeaponsForTest();
        }
#endif

        // Registrar listener para detectar cambios de escena
        SceneManager.sceneLoaded += OnSceneLoaded;
    }

    // ==========================
    // Reset TOTAL (nueva partida)
    // ==========================
    public void ResetAll()
    {
        playerMaxHP      = _initial_playerMaxHP;
        playerCurrentHP  = _initial_playerMaxHP; // vida llena

        gold             = _initial_gold;

        hpLevel          = _initial_hpLevel;
        speedLevel       = _initial_speedLevel;
        resistLevel      = _initial_resistLevel;

        basePriceHP      = _initial_basePriceHP;
        basePriceSpeed   = _initial_basePriceSpeed;
        basePriceResist  = _initial_basePriceResist;
        priceFactor      = _initial_priceFactor;

        totalMinutesPlayed = _initial_totalMinutesPlayed;

        playerLevel      = _initial_playerLevel;
        playerXP         = _initial_playerXP;
        playerXpToNext   = _initial_playerXpToNext;

        equippedWeaponId = _initial_equippedWeaponId;
        equippedWeaponIndex = _initial_equippedWeaponIndex;

        hasCompletedIntro = false;
        highestLevelUnlocked = _initial_highestLevelUnlocked;
        unlockedWeapons.Clear();

        unlockedItems = new System.Collections.Generic.List<string>(_initial_unlockedItems);
        equippedItems = new string[3];
        if (_initial_equippedItems != null)
        {
            for (int i = 0; i < Mathf.Min(3, _initial_equippedItems.Length); i++)
                equippedItems[i] = _initial_equippedItems[i];
        }

        itemLevelKeys = new System.Collections.Generic.List<string>(_initial_itemLevelKeys);
        itemLevelValues = new System.Collections.Generic.List<int>(_initial_itemLevelValues);

        movedW = movedA = movedS = movedD = false;

        tempGold = 0;
        tempXP = 0f;

        baseRegenPerSecond = _initial_baseRegen;
        regenPerSecond     = _initial_regen;

        RecomputeShopMultipliers();

        Debug.Log("[GameSession] ResetAll() - sesión reiniciada a valores base.");
    }

    public void ResetToDefaults() => ResetAll();

    /// <summary>
    /// Guarda en memoria el estado con el que el jugador entra al nivel actual.
    /// Las colecciones se copian para impedir que el progreso del intento modifique el checkpoint.
    /// </summary>
    public void CaptureLevelCheckpoint()
    {
        _levelCheckpoint = new LevelCheckpoint
        {
            playerMaxHP = playerMaxHP,
            playerCurrentHP = playerCurrentHP,
            gold = gold,
            tempGold = tempGold,
            tempXP = tempXP,
            baseRegenPerSecond = baseRegenPerSecond,
            regenPerSecond = regenPerSecond,
            totalMinutesPlayed = totalMinutesPlayed,
            playerLevel = playerLevel,
            playerXP = playerXP,
            playerXpToNext = playerXpToNext,
            equippedWeaponId = equippedWeaponId,
            equippedWeaponIndex = equippedWeaponIndex,
            hasCompletedIntro = hasCompletedIntro,
            highestLevelUnlocked = highestLevelUnlocked,
            unlockedWeapons = new System.Collections.Generic.List<string>(unlockedWeapons),
            unlockedItems = new System.Collections.Generic.List<string>(unlockedItems),
            equippedItems = equippedItems != null ? (string[])equippedItems.Clone() : new string[3],
            itemLevelKeys = new System.Collections.Generic.List<string>(itemLevelKeys),
            itemLevelValues = new System.Collections.Generic.List<int>(itemLevelValues),
            hpLevel = hpLevel,
            speedLevel = speedLevel,
            resistLevel = resistLevel
        };

        Debug.Log("[GameSession] Checkpoint de entrada al nivel capturado.");
    }

    /// <summary>Restaura el checkpoint de entrada al nivel. Devuelve false si no existe.</summary>
    public bool RestoreLevelCheckpoint()
    {
        if (_levelCheckpoint == null)
        {
            Debug.LogWarning("[GameSession] No existe un checkpoint de nivel para restaurar. Aplicando FullHeal y descarte de run.");
            DiscardRunRewards();
            FullHeal();
            return true;
        }

        playerMaxHP = _levelCheckpoint.playerMaxHP;
        playerCurrentHP = _levelCheckpoint.playerCurrentHP;
        gold = _levelCheckpoint.gold;
        tempGold = _levelCheckpoint.tempGold;
        tempXP = _levelCheckpoint.tempXP;
        baseRegenPerSecond = _levelCheckpoint.baseRegenPerSecond;
        regenPerSecond = _levelCheckpoint.regenPerSecond;
        totalMinutesPlayed = _levelCheckpoint.totalMinutesPlayed;
        playerLevel = _levelCheckpoint.playerLevel;
        playerXP = _levelCheckpoint.playerXP;
        playerXpToNext = _levelCheckpoint.playerXpToNext;
        equippedWeaponId = _levelCheckpoint.equippedWeaponId;
        equippedWeaponIndex = _levelCheckpoint.equippedWeaponIndex;
        equippedWeapon = null;
        hasCompletedIntro = _levelCheckpoint.hasCompletedIntro;
        highestLevelUnlocked = _levelCheckpoint.highestLevelUnlocked;
        unlockedWeapons = new System.Collections.Generic.List<string>(_levelCheckpoint.unlockedWeapons);
        unlockedItems = new System.Collections.Generic.List<string>(_levelCheckpoint.unlockedItems);
        equippedItems = (string[])_levelCheckpoint.equippedItems.Clone();
        itemLevelKeys = new System.Collections.Generic.List<string>(_levelCheckpoint.itemLevelKeys);
        itemLevelValues = new System.Collections.Generic.List<int>(_levelCheckpoint.itemLevelValues);
        hpLevel = _levelCheckpoint.hpLevel;
        speedLevel = _levelCheckpoint.speedLevel;
        resistLevel = _levelCheckpoint.resistLevel;

        RecomputeShopMultipliers();
        Debug.Log("[GameSession] Checkpoint de nivel restaurado para reintentar.");
        return true;
    }

    /// <summary>Descarta el checkpoint temporal al abandonar o completar un nivel.</summary>
    public void ClearLevelCheckpoint()
    {
        _levelCheckpoint = null;
    }

    // ==========================
    // Detección de cambio de escena
    // ==========================
    void OnSceneLoaded(Scene scene, LoadSceneMode mode)
    {
        // Si se carga la escena MenuScene, reiniciar todos los valores
        if (scene.name == "MenuScene")
        {
            ResetAll();
            ClearLevelCheckpoint();
            Debug.Log("[GameSession] MenuScene cargada - valores reiniciados a base.");
        }

        // Si se carga el HUB, curar al máximo
        if (scene.name == "LevelHUB")
        {
            ClearLevelCheckpoint();
            FullHeal();
            var shop = FindFirstObjectByType<ShopController>();
            if (shop != null) shop.ResetRerollCost();
            Debug.Log("[GameSession] LevelHUB cargada - FullHeal + ResetRerollCost aplicados.");
        }

        // SIEMPRE: pasar weaponIndex al jugador de la nueva escena
        var slotManager = FindFirstObjectByType<WeaponSlotManager>();
        if (slotManager != null)
        {
            slotManager.SetWeaponIndex(equippedWeaponIndex);
            Debug.Log($"[GameSession] OnSceneLoaded → WeaponSlotManager.SetWeaponIndex({equippedWeaponIndex})");
        }

        if (scene.name == "LevelWoods")
            CaptureLevelCheckpoint();
    }

    // ==========================
    // Carga de Partida (SaveData)
    // ==========================
    public void ImportSaveData(SaveData data)
    {
        if (data == null) return;

        playerMaxHP = data.playerMaxHP;
        playerCurrentHP = data.playerCurrentHP;
        gold = data.gold;
        
        playerLevel = data.playerLevel;
        playerXP = data.playerXP;
        playerXpToNext = data.playerXpToNext;
        
        equippedWeaponId = data.equippedWeaponId;
        equippedWeaponIndex = data.equippedWeaponIndex;

        hasCompletedIntro = data.hasCompletedIntro;
        highestLevelUnlocked = data.highestLevelUnlocked;
        unlockedWeapons = data.unlockedWeapons != null ? new System.Collections.Generic.List<string>(data.unlockedWeapons) : new System.Collections.Generic.List<string>();

        unlockedItems = data.unlockedItems != null ? new System.Collections.Generic.List<string>(data.unlockedItems) : new System.Collections.Generic.List<string>();
        equippedItems = data.equippedItems != null ? new string[3] { data.equippedItems[0], data.equippedItems[1], data.equippedItems[2] } : new string[3];

        itemLevelKeys = data.itemLevelKeys != null
            ? new System.Collections.Generic.List<string>(data.itemLevelKeys)
            : new System.Collections.Generic.List<string>();
        itemLevelValues = data.itemLevelValues != null
            ? new System.Collections.Generic.List<int>(data.itemLevelValues)
            : new System.Collections.Generic.List<int>();

        hpLevel = data.hpLevel;
        speedLevel = data.speedLevel;
        resistLevel = data.resistLevel;

        RecomputeShopMultipliers();
        Debug.Log("[GameSession] Datos importados exitosamente desde SaveData.");
    }

    void OnDestroy()
    {
        if (_instance == this)
        {
            _instance = null;
        }
        SceneManager.sceneLoaded -= OnSceneLoaded;
    }
